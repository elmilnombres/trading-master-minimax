"""
Strategy adapters — one per bot, stateless.

Owned by core/strategy/.
No exchange calls. No state mutations. Pure input → output.

Each adapter translates Phase 2 analysis outputs into a Signal
per the approved Signal Construction Contract.

Candle batches are provided as explicit arguments by BotRuntime
(MarketDataProvider.get_multi_timeframe_candles). Adapters do NOT
fetch market data internally.

Frozen Signal Construction Contract (Phase 4):
  ALPHA:  MacroBias.state → direction
          Top-ranked POI → entry zone (re-detect, resolve by poi.relevant_poi_id)
          Zone POI → structural stop (zone edge)
          Point POI → ATR14(M15) stop
          TP1 = 2R, TP2 = 3R
          H4 gate: h4_candle_closed == True required

  BETA:   validate_beta_sequence() → valid + direction
          M15 mitigation FVG midpoint → entry
          FVG zone edge → stop
          TP1 = 2R, TP2 = 3R
          Sweep level: PDH/PDL primary, session high/low secondary

  GAMMA:  validate_gamma_sequence() → valid + direction
          ReclaimResult.reclaim_price → entry
          LiquiditySweep.sweep_price → stop
          TP1 = 2R, TP2 = 3R
          ATR metadata: ATR14(M5)

  TP2 is persisted in Signal.take_profit_2. Exchange-attached TP in Phase 4
  uses only TP1 (Bybit native tp_trigger_price).
"""

